    private static readonly Dictionary<string, DiagnosisCode> ByCode = All.ToDictionary(d => d.Code, StringComparer.OrdinalIgnoreCase);

    /// <summary>The entry with this code (case-insensitive), or null when the code isn't on the list.</summary>
    public static DiagnosisCode? Find(string? code) =>
        code is not null && ByCode.TryGetValue(code.Trim(), out var d) ? d : null;

    /// <summary>
    /// Up to <see cref="MaxResults"/> entries whose name contains <paramref name="q"/> or whose code starts with it (case-insensitive):
    /// an exact code first, then codes starting with it, then names starting with it, then the rest, each by name. A blank query gives
    /// the first entries by name.
    /// </summary>
    public static IReadOnlyList<DiagnosisCode> Search(string? q)
    {
        var term = q?.Trim() ?? "";
        if (term.Length == 0) return All.OrderBy(d => d.Name, StringComparer.OrdinalIgnoreCase).Take(MaxResults).ToList();
        return All
            .Select(d => (Entry: d, Rank:
                d.Code.Equals(term, StringComparison.OrdinalIgnoreCase) ? 0
                : d.Code.StartsWith(term, StringComparison.OrdinalIgnoreCase) ? 1
                : d.Name.StartsWith(term, StringComparison.OrdinalIgnoreCase) ? 2
                : d.Name.Contains(term, StringComparison.OrdinalIgnoreCase) ? 3
                : -1))
            .Where(x => x.Rank >= 0)
            .OrderBy(x => x.Rank).ThenBy(x => x.Entry.Name, StringComparer.OrdinalIgnoreCase)
            .Take(MaxResults).Select(x => x.Entry).ToList();
    }
